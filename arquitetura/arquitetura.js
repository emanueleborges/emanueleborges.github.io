// Abas: ?p= escolhe o projeto (o card do portfólio abre direto no certo); trocar de aba atualiza o endereço.
const abas = [...document.querySelectorAll("[data-aba]")];
const mostrar = (id, { foco = false } = {}) => {
  const atual = abas.find((aba) => aba.dataset.aba === id) ?? abas[0];
  for (const aba of abas) {
    const ativa = aba === atual;
    aba.setAttribute("aria-selected", String(ativa));
    aba.tabIndex = ativa ? 0 : -1;
    document.getElementById(aba.dataset.aba).hidden = !ativa;
  }
  if (foco) atual.focus();
  return atual.dataset.aba;
};

mostrar(new URLSearchParams(location.search).get("p"));
for (const aba of abas) {
  aba.addEventListener("click", () => {
    const url = new URL(location.href);
    url.searchParams.set("p", mostrar(aba.dataset.aba));
    history.replaceState(null, "", url);
  });
  // Setas do teclado entre as abas (padrão WAI-ARIA de tabs).
  aba.addEventListener("keydown", (event) => {
    const passo = { ArrowRight: 1, ArrowLeft: -1 }[event.key];
    if (!passo) return;
    const proxima = abas[(abas.indexOf(aba) + passo + abas.length) % abas.length];
    mostrar(proxima.dataset.aba, { foco: true });
    proxima.click();
  });
}

