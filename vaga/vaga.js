const fold = (value) => value.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
const pillarOf = (requirement) => PILLARS.find(([, pattern]) => pattern.test(fold(requirement)))?.[0] ?? "other";
const PILLAR_LABEL = { backend: "skills.tab.backend", frontend: "skills.tab.frontend", ia: "skills.tab.ia", dados: "skills.tab.dados", devops: "skills.tab.devops" };

// Nota de cada pilar com a mesma regra do Worker: obrigatório pesa 2, desejável 1; atende = 1, parcial = 0,5.
function pillarScores(requirements) {
  const weight = (r) => (r.importance === "must" ? 2 : 1);
  const value = { strong: 1, partial: 0.5, none: 0 };
  const groups = new Map();
  requirements.forEach((r) => {
    const key = pillarOf(r.requirement);
    groups.set(key, [...(groups.get(key) ?? []), r]);
  });
  return [...groups]
    .map(([key, list]) => ({
      key,
      label: key === "other" ? t("other") : siteText(PILLAR_LABEL[key]) || key,
      count: list.length,
      score: Math.round((100 * list.reduce((s, r) => s + weight(r) * value[r.level], 0)) / list.reduce((s, r) => s + weight(r), 0)),
    }))
    .sort((a, b) => ["backend", "frontend", "ia", "dados", "devops", "other"].indexOf(a.key) - ["backend", "frontend", "ia", "dados", "devops", "other"].indexOf(b.key));
}

// Radar com 3 pilares ou mais; com menos, barras (um radar de 2 eixos não diz nada).
function pillarChart(pillars) {
  const bars = `<ul class="pillar-bars">${pillars
    .map((p) => `<li><span>${escape(p.label)} <small>(${p.count})</small></span><span class="bar"><i style="width:${p.score}%"></i></span><strong>${p.score}%</strong></li>`)
    .join("")}</ul>`;
  if (pillars.length < 3) return bars;
  const R = 70;
  const point = (i, r) => {
    const a = (i / pillars.length) * 2 * Math.PI - Math.PI / 2;
    return [Math.cos(a) * r, Math.sin(a) * r];
  };
  const polygon = (r) => pillars.map((_, i) => point(i, typeof r === "function" ? r(i) : r).map((v) => v.toFixed(1)).join(",")).join(" ");
  const grid = [0.25, 0.5, 0.75, 1].map((f) => `<polygon points="${polygon(R * f)}" fill="none" style="stroke:var(--line)"/>`).join("");
  const axes = pillars.map((_, i) => `<line x1="0" y1="0" x2="${point(i, R)[0].toFixed(1)}" y2="${point(i, R)[1].toFixed(1)}" style="stroke:var(--line)"/>`).join("");
  const labels = pillars
    .map((p, i) => {
      const [x, y] = point(i, R + 14);
      const anchor = Math.abs(x) < 4 ? "middle" : x > 0 ? "start" : "end";
      return `<text x="${x.toFixed(1)}" y="${y.toFixed(1)}" text-anchor="${anchor}" dominant-baseline="central">${escape(p.label)} · ${p.score}%</text>`;
    })
    .join("");
  const shape = polygon((i) => (R * Math.max(pillars[i].score, 3)) / 100);
  const dots = pillars.map((p, i) => `<circle cx="${point(i, (R * Math.max(p.score, 3)) / 100)[0].toFixed(1)}" cy="${point(i, (R * Math.max(p.score, 3)) / 100)[1].toFixed(1)}" r="3" style="fill:var(--accent)"/>`).join("");
  return `<svg class="radar" viewBox="-150 -100 300 200" role="img" aria-label="${escape(pillars.map((p) => `${p.label}: ${p.score}%`).join("; "))}">${grid}${axes}<polygon class="radar-shape" points="${shape}" style="fill:rgba(var(--accent-rgb),.22);stroke:var(--accent)" stroke-width="2"/>${dots}${labels}</svg>${bars}`;
}

function renderResult() {
  const result = lastResult;
  if (!result) return;
  $("[data-ring]").innerHTML = gauge(result.score);
  // O ponteiro parte do zero e gira até a nota (o CSS anima a troca de ângulo).
  const needle = $("[data-ring] .gauge-needle");
  needle.classList.add("is-start");
  needle.getBoundingClientRect(); // aplica a posição inicial antes de animar
  needle.classList.remove("is-start");
  $("[data-pillars-title]").textContent = `// ${t("pillars").toUpperCase()}`;
  $("[data-pillars]").innerHTML = pillarChart(pillarScores(result.requirements));
  $("[data-role]").textContent = result.role;
  const count = (level) => result.requirements.filter((r) => r.level === level).length;
  $("[data-tally]").innerHTML = ["strong", "partial", "none"].map((l) => `<span class="pill">${ICON[l]} ${escape(t(l))}: ${count(l)}</span>`).join("");
  $("[data-reqs]").innerHTML = result.requirements
    .map((r) => `<li class="req">
        <span class="icon" aria-hidden="true">${ICON[r.level]}</span>
        <div><strong>${escape(r.requirement)}</strong><span class="tag">${escape(t(r.importance))}</span></div>
        <div><span class="level ${r.level}">${escape(t(r.level))}</span><p>${escape(r.reason || t(r.level === "none" ? "noReason" : "seeEvidence"))}</p></div>
        ${r.evidence.length ? `<div class="evidence">${r.evidence.map(evidenceLink).join("")}</div>` : "<div></div>"}
      </li>`)
    .join("");
  $("[data-pitch]").textContent = result.pitch;
  $("[data-cv]").href = new URL(globalThis.PERFIL.cvPdf(Demo.lang), `${location.origin}/`).href; // PDF do Worker (ou a impressão)
  $("[data-contact]").href = `/?lang=${Demo.lang}#contato`;
}

function setBusy(busy) {
  $("[data-form]").classList.toggle("is-scanning", busy);
  $("[data-submit]").disabled = busy;
  $("[data-submit]").textContent = t(busy ? "analyzing" : "analyze");
  $("[data-loading]").hidden = !busy;
}

let stepTimer = null;
function cycleSteps() {
  const steps = ["step1", "step2", "step3", "step4"];
  let i = 0;
  $("[data-loading-text]").textContent = t(steps[0]);
  clearInterval(stepTimer);
  stepTimer = setInterval(() => {
    i = Math.min(i + 1, steps.length - 1);
    $("[data-loading-text]").textContent = t(steps[i]);
  }, 2500);
}

async function analyze(event) {
  event.preventDefault();
  const job = $("[data-job]").value.trim();
  const status = $("[data-status]");
  status.textContent = "";
  if (job.length < 80) {
    status.textContent = t("tooShort");
    return;
  }
  setBusy(true);
  cycleSteps();
  const { ok, status: code, data } = await PortfolioApi.post("/match", { job, lang: Demo.lang }, 60000);
  clearInterval(stepTimer);
  setBusy(false);
  if (!ok || !data?.requirements) {
    const message = { 429: "rateLimited", 503: "unavailable", 403: "blocked", 400: "tooShort" }[code] ?? (code === 0 ? "blocked" : "failed");
    status.textContent = t(message);
    return;
  }
  lastResult = data;
  renderResult();
  $("[data-result]").hidden = false;
  $("[data-result]").scrollIntoView({ behavior: matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "start" });
}

function init() {
  // Rótulos das evidências vêm do i18n do site: ao abrir e a cada troca, baixa o idioma (se preciso) e redesenha.
  document.addEventListener("languagechange", () => window.I18N?.load?.(Demo.lang).then((ok) => ok && renderResult()));
  Demo.setup(T, () => {
    setBusy(false);
    renderResult();
  });
  setBusy(false);
  const job = $("[data-job]");
  const updateCount = () => ($("[data-count]").textContent = job.value.length);
  job.addEventListener("input", updateCount);
  $("[data-form]").addEventListener("submit", analyze);
  $("[data-sample]").addEventListener("click", () => {
    job.value = SAMPLE_JOB;
    updateCount();
    job.focus();
  });
  $("[data-copy]").addEventListener("click", async () => {
    const text = `${lastResult.role} — ${lastResult.score}% ${t("score")}\n\n${lastResult.pitch}\n\n${globalThis.PERFIL.site}`;
    try {
      await navigator.clipboard.writeText(text);
      $("[data-copy]").textContent = t("copied");
      setTimeout(() => ($("[data-copy]").textContent = t("copy")), 2000);
    } catch {
      /* sem permissão de área de transferência */
    }
  });
  $("[data-again]").addEventListener("click", () => {
    $("[data-result]").hidden = true;
    job.value = "";
    updateCount();
    job.focus();
    scrollTo({ top: 0 });
  });
}

