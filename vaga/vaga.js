const PROJECT_NAMES = { p6: "Products API", p7: "Movie Recommender System", p8: "Face Recognition POC", p9: "Kotlin Desktop CRUD" };
const JOB_ORG = { job1: "INDT", job2: "ICCT", job3: "SEMEF / SEMAD" };
function evidenceLink(id) {
  const sec = T[Demo.lang]?.sec ?? T.en.sec;
  let section = "sobre";
  let label = sec.about;
  if (JOB_ORG[id]) [section, label] = ["experiencia", `${sec.experience}: ${JOB_ORG[id]}`];
  else if (id === "years" || id === "current" || id === "public-sector") [section, label] = ["experiencia", sec.experience];
  else if (/^p\d+$/.test(id)) [section, label] = ["projetos", `${sec.projects}: ${PROJECT_NAMES[id] ?? siteText(`${id}.title`)}`];
  else if (id === "portfolio") [section, label] = ["projetos", `${sec.projects}: ${siteText("p10.title")}`];
  else if (id.startsWith("skills-")) {
    const cat = { "skills-backend": "skills.tab.backend", "skills-frontend": "skills.tab.frontend", "skills-ai": "skills.tab.ia", "skills-data": "skills.tab.dados", "skills-devops": "skills.tab.devops", "skills-practices": "skills.tab.praticas" }[id];
    [section, label] = ["habilidades", `${sec.skills}: ${siteText(cat)}`];
  } else if (/^edu\d$/.test(id)) [section, label] = ["formacao", siteText(`edu.d${id.slice(3)}`)];
  else if (id === "certifications" || id === "languages") [section, label] = ["formacao", sec.education];
  else if (id === "contact") [section, label] = ["contato", sec.contact];
  return `<a href="/?lang=${Demo.lang}#${section}">${escape(label || sec.about)}</a>`;
}

// Velocímetro (meio círculo) com a nota; o ponteiro sai do zero e gira até a nota.
function gauge(value) {
  const score = Math.max(0, Math.min(100, Math.round(Number(value) || 0)));
  const ticks = [0, 25, 50, 75, 100]
    .map((tick) => {
      const a = Math.PI * (1 - tick / 100);
      const [x1, y1, x2, y2] = [100 + Math.cos(a) * 92, 104 - Math.sin(a) * 92, 100 + Math.cos(a) * 84, 104 - Math.sin(a) * 84];
      return `<line x1="${x1.toFixed(1)}" y1="${y1.toFixed(1)}" x2="${x2.toFixed(1)}" y2="${y2.toFixed(1)}" style="stroke:var(--line-strong)" stroke-width="2"/>`;
    })
    .join("");
  return `<svg viewBox="0 0 200 116" aria-hidden="true">
      <defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" style="stop-color:var(--accent-2)"/><stop offset="1" style="stop-color:var(--accent)"/></linearGradient></defs>
      <path d="M24 104 A76 76 0 0 1 176 104" fill="none" style="stroke:var(--line)" stroke-width="14" stroke-linecap="round"/>
      <path class="gauge-fill" d="M24 104 A76 76 0 0 1 176 104" fill="none" stroke="url(#g)" stroke-width="14" stroke-linecap="round" pathLength="100" stroke-dasharray="${score} 100"/>
      ${ticks}
      <g class="gauge-needle" style="--angle:${(score / 100) * 180 - 90}deg"><line x1="100" y1="104" x2="100" y2="40" style="stroke:var(--text)" stroke-width="3" stroke-linecap="round"/><circle cx="100" cy="104" r="7" style="fill:var(--text)"/></g>
    </svg><strong aria-label="${score}% ${escape(t("score"))}">${score}%<small>${escape(t("score"))}</small></strong>`;
}

